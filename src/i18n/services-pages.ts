function hasArabic(value: string) {
  return ARABIC_SCRIPT.test(value);
}

function localizeItem(
  item: ServiceItem,
  copy: { title: string; description: string } | undefined,
): ServiceItem {
  if (!copy) return item;

  return {
    ...item,
    title: hasArabic(item.title) ? item.title : copy.title,
    description: hasArabic(item.description) ? item.description : copy.description,
  };
}

export function localizeServicePage(
  service: ServicePageData,
  locale: Locale,
): ServicePageData {
  if (locale !== "ar") return service;

  const copy = COPY_AR[service.slug];
  if (!copy) return service;

  return {
    ...service,
    title: hasArabic(service.title) ? service.title : copy.title,
    eyebrow: hasArabic(service.eyebrow) ? service.eyebrow : copy.eyebrow,
    summary: hasArabic(service.summary) ? service.summary : copy.summary,
    intro: service.intro?.every(hasArabic) ? service.intro : copy.intro,
    offeringsEyebrow: hasArabic(service.offeringsEyebrow)
      ? service.offeringsEyebrow
      : copy.offeringsEyebrow,
    offeringsTitle: hasArabic(service.offeringsTitle)
      ? service.offeringsTitle
      : copy.offeringsTitle,
    items: service.items.map((item, index) => localizeItem(item, copy.items[index])),
  };
}

export function localizeServicePages(
  services: ServicePageData[],
  locale: Locale,
) {
  return services.map((service) => localizeServicePage(service, locale));
}
